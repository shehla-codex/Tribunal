"use client";

import React from "react";
import {
  X,
  Download,
  FileText,
  Gavel,
  Scale,
  TrendingUp,
} from "lucide-react";
import { TrialCase } from "@/lib/schema";
import { formatDocketId, getScoreColor } from "@/lib/storage";

interface CaseReportModalProps {
  trial: TrialCase;
  onClose: () => void;
}

/** Build the Markdown report text entirely in the browser — no server call. */
function buildMarkdown(trial: TrialCase): string {
  const { charges, debate, scores, verdict, appealData } = trial;
  const docket = formatDocketId(trial.id);
  const date = new Date(trial.timestamp).toLocaleDateString("en-US", {
    month: "long",
    day: "numeric",
    year: "numeric",
  });

  const lines: string[] = [];

  lines.push(`# Tribunal Case Report`);
  lines.push(``);
  lines.push(`**Case Title:** ${trial.caseName}`);
  lines.push(`**Docket:** ${docket}`);
  lines.push(`**Date:** ${date}`);
  lines.push(`**Language:** ${trial.language}`);
  lines.push(`**Verdict:** ${verdict.ruling}`);
  lines.push(``);

  // Scores
  lines.push(`## Code Health Score`);
  lines.push(``);
  lines.push(`| Category | Score |`);
  lines.push(`|---|---|`);
  lines.push(`| **Overall** | **${scores.overall} / 100** |`);
  lines.push(`| Logic & Correctness | ${scores.logic} / 100 |`);
  lines.push(`| Security & Vulnerabilities | ${scores.security} / 100 |`);
  lines.push(`| Maintainability & Architecture | ${scores.maintainability} / 100 |`);
  lines.push(``);

  // Summary
  lines.push(`## Chief Justice's Summary`);
  lines.push(``);
  lines.push(`> ${verdict.summary}`);
  lines.push(``);

  // Charges
  lines.push(`## Formal Charges (${charges.length})`);
  lines.push(``);
  charges.forEach((charge, idx) => {
    const loc = charge.file
      ? `${charge.file}${charge.line ? `:${charge.line}` : ""}`
      : charge.line
      ? `Line ${charge.line}`
      : charge.id;
    lines.push(`### ${idx + 1}. ${charge.title}`);
    lines.push(``);
    lines.push(`- **ID:** ${charge.id}`);
    lines.push(`- **Severity:** ${charge.severity}`);
    lines.push(`- **Category:** ${charge.category}`);
    lines.push(`- **Location:** ${loc}`);
    lines.push(``);
    lines.push(charge.description);
    lines.push(``);
  });

  // Sentence (ranked fixes)
  lines.push(`## Sentence — Ranked Actionable Fixes`);
  lines.push(``);
  verdict.sentence.forEach((fix, idx) => {
    lines.push(`${idx + 1}. ${fix}`);
  });
  lines.push(``);

  // Debate transcript
  lines.push(`## Debate Transcript`);
  lines.push(``);
  const speakerLabel: Record<string, string> = {
    prosecutor: "⚖️ Prosecutor Owl",
    defense: "🛡️ Defense Owl",
    judge: "🔨 Chief Justice Owl",
  };
  debate.forEach((turn) => {
    const label = speakerLabel[turn.speaker] || turn.speaker;
    lines.push(`**${label}**`);
    if (turn.objectionText) {
      lines.push(``);
      lines.push(`> *Counsel's Objection:* "${turn.objectionText}"`);
    }
    if (turn.ruling) {
      lines.push(``);
      lines.push(`*Ruling: **${turn.ruling}***`);
    }
    lines.push(``);
    lines.push(turn.text);
    lines.push(``);
    lines.push(`---`);
    lines.push(``);
  });

  // Appeal result (if present)
  if (appealData) {
    lines.push(`## Appeal Result`);
    lines.push(``);
    lines.push(
      `| Prior Score | Appealed Score | Improvement |`
    );
    lines.push(`|---|---|---|`);
    lines.push(
      `| ${appealData.previousScore} | ${appealData.newScore} | +${appealData.newScore - appealData.previousScore} pts |`
    );
    lines.push(``);
    lines.push(`### Implemented Fixes`);
    lines.push(``);
    appealData.improvements.forEach((imp) => {
      lines.push(`- ${imp}`);
    });
    lines.push(``);
  }

  lines.push(`---`);
  lines.push(`*Generated by [Tribunal](https://github.com/) — Your code. Put on trial.*`);

  return lines.join("\n");
}

/** Trigger a browser file download of the Markdown text — no server needed. */
function downloadMarkdown(trial: TrialCase): void {
  const md = buildMarkdown(trial);
  const docket = formatDocketId(trial.id)
    .replace(/[^a-zA-Z0-9-]/g, "-")
    .replace(/-+/g, "-")
    .toLowerCase();
  const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `tribunal-case-report-${docket}.md`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

